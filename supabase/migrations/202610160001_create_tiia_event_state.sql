create or replace function public.update_tiia_event_state(
  p_expected_version bigint,
  p_event_data jsonb,
  p_site_config jsonb,
  p_admin_user_id text,
  p_action text
)
returns setof public.tiia_event_state
language plpgsql
security invoker
set search_path = public
as $$
declare
  updated_row public.tiia_event_state;
begin
  if p_admin_user_id is null or p_action is null or p_action not in ('event.updated', 'config.updated') then
    raise exception 'Invalid administrator audit context';
  end if;

  update public.tiia_event_state
     set event_data = p_event_data,
         site_config = p_site_config,
         version = version + 1,
         updated_at = now()
   where id = 1 and version = p_expected_version
  returning * into updated_row;

  if not found then return; end if;

  insert into public.tiia_admin_audit (admin_user_id, action, version_before, version_after)
  values (p_admin_user_id, p_action, p_expected_version, updated_row.version);

  return next updated_row;
end;
$$;

revoke all on public.tiia_event_state from anon, authenticated;
revoke all on function public.update_tiia_event_state(bigint, jsonb, jsonb, text, text) from public, anon, authenticated;
grant select, update on public.tiia_event_state to service_role;
grant execute on function public.update_tiia_event_state(bigint, jsonb, jsonb, text, text) to service_role;

