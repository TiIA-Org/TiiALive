create table if not exists public.tiia_admin_rate_limits (
  key_hash text primary key check (length(key_hash) = 64),
  window_started timestamptz not null,
  attempts integer not null check (attempts > 0)
);

create index if not exists tiia_admin_rate_limits_window_idx on public.tiia_admin_rate_limits (window_started);
alter table public.tiia_admin_rate_limits enable row level security;
revoke all on public.tiia_admin_rate_limits from public, anon, authenticated;
grant select, insert, update, delete on public.tiia_admin_rate_limits to service_role;

create or replace function public.check_tiia_admin_rate_limit(
  p_key_hash text,
  p_max_attempts integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security invoker
set search_path = public
as $$
declare
  current_attempts integer;
  v_now timestamptz := now();
begin
  if p_key_hash is null or p_key_hash !~ '^[a-f0-9]{64}$' or p_max_attempts is null or p_max_attempts < 1 or
     p_window_seconds is null or p_window_seconds < 1 or p_window_seconds > 3600 then
    raise exception 'Invalid rate-limit parameters';
  end if;

  delete from public.tiia_admin_rate_limits
   where window_started < v_now - interval '1 day';

  insert into public.tiia_admin_rate_limits (key_hash, window_started, attempts)
  values (p_key_hash, v_now, 1)
  on conflict (key_hash) do update
     set window_started = case
           when public.tiia_admin_rate_limits.window_started + make_interval(secs => p_window_seconds) <= v_now then v_now
           else public.tiia_admin_rate_limits.window_started
         end,
         attempts = case
           when public.tiia_admin_rate_limits.window_started + make_interval(secs => p_window_seconds) <= v_now then 1
           else public.tiia_admin_rate_limits.attempts + 1
         end
  returning attempts into current_attempts;

  return current_attempts <= p_max_attempts;
end;
$$;

revoke all on function public.check_tiia_admin_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.check_tiia_admin_rate_limit(text, integer, integer) to service_role;
